# | Symbol | Meaning                  |
# | ------ | ------------------------ |
# | `.`    | Any character            |
# | `^`    | Start of string          |
# | `$`    | End of string            |
# | `*`    | 0 or more times          |
# | `+`    | 1 or more times          |
# | `?`    | 0 or 1 time              |
# | `{}`   | Specific number of times |
# | `[]`   | Set of characters        |
# | `\`    | Escape character         |


